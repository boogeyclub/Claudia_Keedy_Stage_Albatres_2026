CREATE CONSTRAINT TRIGGER trg_utilisateurs_require_client_profile
AFTER INSERT OR UPDATE OR DELETE ON gu.utilisateurs
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_exactly_one_client_profile();

