-- Table: Connected browser sessions
-- One row is created after each successful login. The raw servlet/JSESSIONID value is never
-- stored; session_hash is a SHA-256 hash so several browser sessions can be managed safely.
CREATE TABLE IF NOT EXISTS gu.sessions_utilisateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    session_hash CHAR(64) NOT NULL,
    browser_label VARCHAR(120) NOT NULL,
    remember_me BOOLEAN NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    invalidated_at TIMESTAMPTZ,
    CONSTRAINT uq_sessions_utilisateur_session_hash UNIQUE (session_hash),
    CONSTRAINT chk_sessions_utilisateur_dates CHECK (
        last_seen_at >= date_creation
        AND expires_at >= last_seen_at
        AND (invalidated_at IS NULL OR invalidated_at >= date_creation)
    )
);

CREATE INDEX IF NOT EXISTS idx_sessions_utilisateur_utilisateur_active
    ON gu.sessions_utilisateur (utilisateur_id, last_seen_at DESC)
    WHERE invalidated_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_utilisateur_expiration_active
    ON gu.sessions_utilisateur (expires_at)
    WHERE invalidated_at IS NULL;

-- Table: Registration confirmations
-- A pending utilisateur receives one hashed, single-use email-confirmation token.
-- Raw tokens are deliberately never stored in PostgreSQL.
CREATE TABLE IF NOT EXISTS gu.registration_confirmation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_registration_confirmation_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT uq_registration_confirmation_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_registration_confirmation_dates CHECK (
        confirmed_at IS NULL OR confirmed_at <= expires_at
    )
);

CREATE INDEX IF NOT EXISTS idx_registration_confirmation_expiration
    ON gu.registration_confirmation (expires_at)
    WHERE confirmed_at IS NULL;

-- Table: Password-reset requests
-- Only active (therefore confirmed) utilisateurs receive a reset link. The raw link token is
-- never stored; only its SHA-256 hash is persisted. A new request replaces a prior unused token.
CREATE TABLE IF NOT EXISTS gu.password_reset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_password_reset_dates CHECK (
        used_at IS NULL OR used_at <= expires_at
    )
);

CREATE INDEX IF NOT EXISTS idx_password_reset_expiration
    ON gu.password_reset (expires_at)
    WHERE used_at IS NULL;

