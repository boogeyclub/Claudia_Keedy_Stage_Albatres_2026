-- A lot belongs to an active VENDEUR account.
CREATE OR REPLACE FUNCTION gu.enforce_lot_vendeur()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    vendeur_code VARCHAR(50);
    vendeur_statut VARCHAR(30);
BEGIN
    SELECT tu.code, u.statut
    INTO vendeur_code, vendeur_statut
    FROM gu.utilisateurs u
    INNER JOIN gu.type_utilisateur tu ON tu.id = u.type_utilisateur_id
    WHERE u.id = NEW.vendeur_id;

    IF vendeur_code IS NULL OR vendeur_code <> 'VENDEUR' OR vendeur_statut <> 'ACTIF' THEN
        RAISE EXCEPTION 'A catalogue lot can only belong to an active VENDEUR account.';
    END IF;

    NEW.date_mise_a_jour := COALESCE(NEW.date_mise_a_jour, CURRENT_TIMESTAMP);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_lots_enforce_vendeur ON gu.lots;

CREATE TRIGGER trg_lots_enforce_vendeur
BEFORE INSERT OR UPDATE ON gu.lots
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_lot_vendeur();

-- A conversation is opened by a CLIENT about a lot, with that lot's owner as vendeur.
CREATE OR REPLACE FUNCTION gu.enforce_conversation_participants()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    lot_vendeur_id BIGINT;
    client_code VARCHAR(50);
BEGIN
    SELECT l.vendeur_id INTO lot_vendeur_id
    FROM gu.lots l
    WHERE l.id = NEW.lot_id;

    IF lot_vendeur_id IS NULL THEN
        RAISE EXCEPTION 'The conversation lot does not exist.';
    END IF;

    IF NEW.vendeur_id <> lot_vendeur_id THEN
        RAISE EXCEPTION 'The conversation vendeur must be the lot owner.';
    END IF;

    SELECT tu.code INTO client_code
    FROM gu.utilisateurs u
    INNER JOIN gu.type_utilisateur tu ON tu.id = u.type_utilisateur_id
    WHERE u.id = NEW.client_id;

    IF client_code IS NULL OR client_code <> 'CLIENT' THEN
        RAISE EXCEPTION 'Only a CLIENT account can open a catalogue conversation.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_conversations_enforce_participants ON gu.conversations;

CREATE TRIGGER trg_conversations_enforce_participants
BEFORE INSERT OR UPDATE OF lot_id, client_id, vendeur_id ON gu.conversations
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_conversation_participants();

-- Messages, negotiations and visits can only be posted by a participant of the thread.
CREATE OR REPLACE FUNCTION gu.enforce_conversation_actor()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    actor_id BIGINT;
    is_participant BOOLEAN;
BEGIN
    IF TG_ARGV[0] = 'expediteur_id' THEN
        actor_id := NEW.expediteur_id;
    ELSIF TG_ARGV[0] = 'proposeur_id' THEN
        actor_id := NEW.proposeur_id;
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM gu.conversations c
        WHERE c.id = NEW.conversation_id
          AND actor_id IN (c.client_id, c.vendeur_id)
    ) INTO is_participant;

    IF NOT is_participant THEN
        RAISE EXCEPTION 'Only a conversation participant can post in this thread.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_messages_enforce_actor ON gu.messages;
CREATE TRIGGER trg_messages_enforce_actor
BEFORE INSERT OR UPDATE OF conversation_id, expediteur_id ON gu.messages
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_conversation_actor('expediteur_id');

DROP TRIGGER IF EXISTS trg_negociations_enforce_actor ON gu.negociations;
CREATE TRIGGER trg_negociations_enforce_actor
BEFORE INSERT OR UPDATE OF conversation_id, proposeur_id ON gu.negociations
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_conversation_actor('proposeur_id');

DROP TRIGGER IF EXISTS trg_rendez_vous_enforce_actor ON gu.rendez_vous;
CREATE TRIGGER trg_rendez_vous_enforce_actor
BEFORE INSERT OR UPDATE OF conversation_id, proposeur_id ON gu.rendez_vous
FOR EACH ROW
EXECUTE FUNCTION gu.enforce_conversation_actor('proposeur_id');

-- A new message refreshes the thread activity timestamp used by the conversation list.
CREATE OR REPLACE FUNCTION gu.touch_conversation_activity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE gu.conversations
    SET dernier_message_at = GREATEST(COALESCE(dernier_message_at, NEW.date_envoi), NEW.date_envoi)
    WHERE id = NEW.conversation_id;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_messages_touch_conversation ON gu.messages;

CREATE TRIGGER trg_messages_touch_conversation
AFTER INSERT ON gu.messages
FOR EACH ROW
EXECUTE FUNCTION gu.touch_conversation_activity();

