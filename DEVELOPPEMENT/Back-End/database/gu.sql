    type_cacao_id BIGINT NOT NULL REFERENCES gu.type_cacao(id),
    titre VARCHAR(150) NOT NULL,
    description TEXT,
    quantite_kg NUMERIC(12,2) NOT NULL,
    quantite_disponible_kg NUMERIC(12,2) NOT NULL,
    prix_kg NUMERIC(12,2) NOT NULL,
    devise VARCHAR(3) NOT NULL DEFAULT 'XAF',
    region_id BIGINT NOT NULL REFERENCES gu.region(id),
    ville_id BIGINT REFERENCES gu.ville(id),
    localisation VARCHAR(200),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    date_recolte DATE,
    date_disponibilite DATE,
    statut VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_publication TIMESTAMPTZ,
    date_mise_a_jour TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_lots_quantites CHECK (
        quantite_kg > 0
        AND quantite_disponible_kg >= 0
        AND quantite_disponible_kg <= quantite_kg
    ),
    CONSTRAINT chk_lots_prix CHECK (prix_kg > 0),
    CONSTRAINT chk_lots_devise CHECK (char_length(devise) = 3),
